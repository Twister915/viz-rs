//! A tiny dependency-free 5x7 bitmap font, drawn with `fill_rect`.
//!
//! The rest of the visualizer renders everything with rectangles, and we never pulled in
//! `SDL2_ttf`, so the command palette / debug UI gets its own pixel font. Each glyph is seven
//! rows of five bits (bit 4 = leftmost pixel). On-pixels in a row are merged into horizontal
//! runs so a glyph costs at most a handful of `fill_rect` calls instead of 35.

use crate::pipeline::VizColor;
use anyhow::{Result, anyhow};
use sdl2::pixels::Color;
use sdl2::rect::Rect;
use sdl2::render::WindowCanvas;

pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;

/// Horizontal pixels advanced per character (glyph width + 1px gap), in unscaled pixels.
pub const ADVANCE: u32 = GLYPH_W + 1;
/// Vertical pixels per text line (glyph height + 2px gap), in unscaled pixels.
pub const LINE: u32 = GLYPH_H + 2;

/// Width in pixels of `text` rendered at `scale` (no trailing gap).
pub fn text_width(scale: u32, text: &str) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 {
        0
    } else {
        (n * ADVANCE as i32 - 1) * scale as i32
    }
}

pub fn advance(scale: u32) -> i32 {
    ADVANCE as i32 * scale as i32
}

pub fn line_height(scale: u32) -> i32 {
    LINE as i32 * scale as i32
}

/// Draw `text` with its top-left corner at (`x`, `y`). Newlines move to the next line.
pub fn draw_text(
    canvas: &mut WindowCanvas,
    x: i32,
    y: i32,
    scale: u32,
    color: VizColor,
    text: &str,
) -> Result<()> {
    canvas.set_draw_color(Color::RGB(color.r, color.g, color.b));
    draw_text_current_color(canvas, x, y, scale, text)
}

fn draw_text_current_color(
    canvas: &mut WindowCanvas,
    x: i32,
    y: i32,
    scale: u32,
    text: &str,
) -> Result<()> {
    let s = scale.max(1) as i32;
    let mut cx = x;
    let mut cy = y;
    for ch in text.chars() {
        if ch == '\n' {
            cx = x;
            cy += line_height(scale);
            continue;
        }
        draw_glyph(canvas, cx, cy, s, ch)?;
        cx += advance(scale);
    }
    Ok(())
}

fn draw_glyph(canvas: &mut WindowCanvas, x: i32, y: i32, s: i32, ch: char) -> Result<()> {
    let rows = glyph(ch);
    for (row_idx, bits) in rows.iter().copied().enumerate() {
        // Walk the 5 columns left-to-right, emitting one rect per maximal run of on-pixels.
        let mut col = 0;
        while col < GLYPH_W {
            let on = (bits >> (GLYPH_W - 1 - col)) & 1 == 1;
            if !on {
                col += 1;
                continue;
            }
            let run_start = col;
            while col < GLYPH_W && (bits >> (GLYPH_W - 1 - col)) & 1 == 1 {
                col += 1;
            }
            let run_len = (col - run_start) as i32;
            let rect = Rect::new(
                x + run_start as i32 * s,
                y + row_idx as i32 * s,
                (run_len * s) as u32,
                s as u32,
            );
            canvas.fill_rect(rect).map_err(|e| anyhow!("sdl2: {}", e))?;
        }
    }
    Ok(())
}

